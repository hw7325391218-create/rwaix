import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { start } from "../src/main.js";

test("paper UI serves the NFT trade first and keeps static files intact", async () => {
  const dataDir = await mkdtemp(join(tmpdir(), "rwaix-ui-"));
  const started = await start({ host: "127.0.0.1", port: 0, dataDir });
  const base = `http://${started.host}:${started.port}`;
  try {
    const health = await fetch(`${base}/health`);
    assert.equal(health.headers.get("x-rwaix-mode"), "paper-test-only");
    const healthBody = await health.json() as { ok: boolean; paperTestOnly: boolean; issuerDid: string };
    assert.equal(healthBody.ok && healthBody.paperTestOnly, true);
    assert.equal(healthBody.issuerDid, "did:web:127.0.0.1%3A8787");
    const did = await fetch(`${base}/did.json`);
    const didBody = await did.json() as { id: string };
    assert.equal(did.status, 200);
    assert.equal(didBody.id, healthBody.issuerDid);
    const wellKnown = await fetch(`${base}/.well-known/did.json`);
    const wellKnownBody = await wellKnown.json() as { id: string };
    assert.equal(wellKnownBody.id, healthBody.issuerDid);
    const page = await fetch(`${base}/`);
    const html = await page.text();
    assert.match(html, /<!doctype html>/i);
    assert.match(html, /type="module"/);
    assert.match(html, /href="\/app\.css"/);
    assert.match(html, /src="\/app\.js"/);
    assert.match(html, /RWAIX/);
    assert.match(html, /NFT/);
    assert.match(html, /实现与测试范围/);
    assert.match(html, /新建本地演示/);
    const script = await fetch(`${base}/app.js`);
    const source = await script.text();
    assert.match(source, /\/api\/scenarios\//);
    assert.match(source, /run\("nft"\)/);
    assert.doesNotMatch(source, /^\{/);
    const catalog = await fetch(`${base}/api/scenarios`);
    const body = await catalog.json() as { scenarios: string[] };
    assert.deepEqual(body.scenarios, ["nft", "identity", "content", "data", "supply", "agent", "compute", "device"]);
    const identity = await fetch(`${base}/api/scenarios/identity/run`, { method: "POST" });
    const report = await identity.json() as { decision: string; feeSplit: Array<{ assetId: string; amount: string }>; reconciliation: { disputesResolvedBySilence: number } };
    assert.equal(report.decision, "ALLOW");
    assert.equal(report.feeSplit[0]?.assetId, "USD_TEST");
    assert.equal(report.feeSplit[0]?.amount, "0");
    assert.equal(report.feeSplit[1]?.assetId, "RWAIX_TEST");
    assert.equal(report.feeSplit[1]?.amount, "0");
    assert.equal(report.reconciliation.disputesResolvedBySilence, 0);
    const nft = await fetch(`${base}/api/scenarios/nft/run`, { method: "POST" });
    const nftReport = await nft.json() as {
      decision: string;
      feeSplit: Array<{ assetId: string; amount: string; state: string }>;
      outOfScope: { decision: string };
      copyrightDecision: string;
      dispute: string;
      reconciliation: { dischargeState?: string; disputesResolvedBySilence: number };
      ledgers: { rights: unknown[] };
      disclosure: { scopeZh: string; unfinishedZh: string };
    };
    assert.equal(nftReport.decision, "ALLOW");
    assert.equal(nftReport.feeSplit[0]?.assetId, "USD_TEST");
    assert.equal(nftReport.feeSplit[0]?.amount, "12000");
    assert.equal(nftReport.feeSplit[1]?.assetId, "RWAIX_TEST");
    assert.equal(nftReport.feeSplit[1]?.amount, "0");
    assert.equal(nftReport.feeSplit[1]?.state, "OPEN");
    assert.equal(nftReport.outOfScope.decision, "DENY");
    assert.equal(nftReport.copyrightDecision, "DENY");
    assert.equal(nftReport.dispute, "OPEN");
    assert.equal(nftReport.reconciliation.dischargeState, "DISCHARGED");
    assert.equal(nftReport.reconciliation.disputesResolvedBySilence, 0);
    assert.equal(nftReport.ledgers.rights.length, 0);
    assert.match(nftReport.disclosure.scopeZh, /12000/);
    assert.match(nftReport.disclosure.unfinishedZh, /未完成的生产条件/);
    const cross = await fetch(`${base}/api/scenarios/cross/run`, { method: "POST" });
    const chain = await cross.json() as { ok: boolean; dispute?: string; trades?: string[] };
    assert.equal(chain.ok, true);
    assert.equal(chain.dispute, "OPEN");
    assert.equal(chain.trades?.length, 3);
    const network = await fetch(`${base}/api/network`);
    const networkBody = await network.json() as { name: string; chainId: number; mainnet: boolean; signsOnBehalf: boolean };
    assert.equal(networkBody.name, "local");
    assert.equal(networkBody.chainId, 31337);
    assert.equal(networkBody.mainnet, false);
    assert.equal(networkBody.signsOnBehalf, false);
    const refused = await fetch(`${base}/api/network/confirm`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ confirmation: "MAINNET" }) });
    assert.equal(refused.status, 403);
    const deploy = await fetch(`${base}/deploy.html`);
    const deployHtml = await deploy.text();
    assert.match(deployHtml, /MAINNET/);
    assert.match(deployHtml, /data-net="local"/);
    assert.match(deployHtml, /no private key/);
    assert.match(deployHtml, /href="\/app\.css"/);
    assert.match(deployHtml, /src="deploy\.js"/);
    assert.doesNotMatch(deployHtml, /type="password"/);
    assert.doesNotMatch(deployHtml, /name="privateKey"/);
    const missing = await fetch(`${base}/%2e%2e/%2e%2e/package.json`);
    assert.notEqual(missing.status, 200);
    assert.doesNotMatch(await missing.text(), /rwaix-reference/);
  } finally {
    started.server.close();
    await rm(dataDir, { recursive: true, force: true });
  }
});
